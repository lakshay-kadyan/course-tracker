"use client";
import Link from "next/link";
import { AlertOctagon, ArrowRight, CalendarX2, Clock, Gauge, Hourglass, ShieldAlert, Sparkles, TriangleAlert } from "lucide-react";
import { Card, Pill } from "@/components/ui";
import { subjectHref } from "@/components/shell/nav";
import type { Role } from "@/lib/types";
import { WARNING_LABEL, type Warning, type WeeklyReport } from "./insights";
import { cn } from "@/lib/utils";

const ICON = { overdue: Clock, missed: CalendarX2, pace: Gauge, hours: Hourglass, exam: AlertOctagon, pending: TriangleAlert };

export function WarningFeed({ warnings, role, limit, more }: { warnings: Warning[]; role: Role; limit?: number; more?: string }) {
  const list = limit ? warnings.slice(0, limit) : warnings;
  if (!list.length) return <div className="flex items-center gap-2 px-4 py-8 text-sm text-slate-400"><ShieldAlert className="h-4 w-4 text-emerald-400" />No active warnings in scope.</div>;
  return (
    <ul className="divide-y divide-line/60">
      {list.map((w) => { const I = ICON[w.kind]; return (
        <li key={w.id}><Link href={subjectHref(role, w.subjectId)} className="flex gap-3 px-4 py-3 transition-colors hover:bg-white/[.03]">
          <span className={cn("mt-0.5 grid h-7 w-7 shrink-0 place-items-center rounded-lg", w.severity === "high" ? "bg-red-500/10 text-red-300" : "bg-amber-500/10 text-amber-300")}><I className="h-3.5 w-3.5" /></span>
          <span className="min-w-0 flex-1"><span className="block text-sm text-slate-100">{w.title}</span><span className="mt-0.5 block text-xs text-slate-400">{w.detail}</span></span>
          <Pill tone={w.severity === "high" ? "red" : "amber"}>{WARNING_LABEL[w.kind]}</Pill>
        </Link></li>); })}
      {more && warnings.length > (limit ?? 0) && <li><Link href={more} className="flex items-center justify-center gap-1 px-4 py-2.5 text-xs text-indigo-300 hover:underline">View all {warnings.length} warnings<ArrowRight className="h-3 w-3" /></Link></li>}
    </ul>
  );
}

export function ReportWidget({ report, href }: { report: WeeklyReport; href?: string }) {
  return (
    <Card className="border-indigo-500/20 bg-gradient-to-br from-[#12193a] to-panel" title={<span className="flex items-center gap-2"><Sparkles className="h-4 w-4 text-violet-300" />AI Weekly Academic Report</span>} subtitle="Demo output generated by rules from sample data. No AI model is connected."
      action={href ? <Link href={href} className="text-xs text-indigo-300 hover:underline">Full report</Link> : undefined}>
      <p className="text-sm leading-relaxed text-slate-200">{report.headline}</p>
      {report.recommendations.length > 0 && (
        <ul className="mt-4 space-y-2">{report.recommendations.slice(0, 3).map((r) => <li key={r.subjectId} className="rounded-lg border border-line bg-black/20 p-2.5 text-xs text-slate-300"><b className="text-white">{r.subject}.</b> {r.text}</li>)}</ul>
      )}
    </Card>
  );
}
